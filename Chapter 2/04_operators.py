# Arithmetic Operators
a = 23
b = 32
c = a+b 
# +, -, *, /, % are all arithmetic operators
print (c)

# Assignment Operators
a = 4-2 # Assign 4-2 in a
print (a)

b = 3
b += 6 # Increase the value of 'b' by 6
# b -= 6 Decrease the value of 'b' by 6 
print (b)

# Comparison Operators 
d = 6==6 
print (d)
e = 5>=5 
print (e)
# '==' '>=' '<=' '>' '<' '!=' are comparison operators 

# Logical Operators
f = True or False 
# Similar to Logic Gates in Semiconductor having 'or' 'and' 'not' gates  
print (f)

# TRUTH TABLE FOR 'or'
print ("True or False is", True or False)
print ("True or True is", True or False)
print ("False or False is", True or False)
print ("False or True is", True or False)

# TRUTH TABLE FOR 'and'
print ("True and False is", True or False)
print ("True and True is", True or False)
print ("False and False is", True or False)
print ("False and True is", True or False)

# FOR 'not'
print (not(True))
