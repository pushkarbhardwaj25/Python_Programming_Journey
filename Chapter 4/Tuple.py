# a tuple is collection of data set like a list but which is immutable like a string
a = (1,2,3,"Paraag")
print(type(a)) # Will give tuple as an output

b = (1)
print(type(b)) # Will give integer as an output

c = (1,)
print(type(c)) # Will give tuple as an output

d = ()
print(type(d))

e = ( )
print(type(e))
